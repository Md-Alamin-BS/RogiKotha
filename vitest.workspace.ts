// ASSUMPTION(T-001): Vitest 4 removed the standalone `defineWorkspace` /
// auto-discovered `vitest.workspace.ts` mechanism the task file specified
// (vitest/config no longer exports `defineWorkspace`; a root config's
// `test.projects` array is the replacement — see ISS-004). This file keeps
// the name and the two globs the task asked for, but is a normal Vitest
// config referenced explicitly via `--config vitest.workspace.ts` from the
// root scripts, since Vitest no longer auto-loads a file with this name.
import { readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vitest/config';

const ROOT = path.dirname(fileURLToPath(import.meta.url));

// T-010 (D10, functional-spec.md § 7): every workspace package's source root, so a file no test
// loads still counts, at 0% (BR6.2).
export const COVERAGE_ROOTS = [
  'packages/domain/src',
  'packages/contracts/src',
  'packages/application/src',
  'packages/database/src',
  'packages/adapters/src',
  'packages/i18n/src',
  'packages/test-support/src',
  'apps/web/src',
  'apps/worker/src',
];

// A file whose header says it is generated and must not be edited by hand is excluded: tests
// cannot raise what a script rewrites (BR6.4, Question 8). Read from the files, not listed, so a
// new generated file is excluded and a hand-written one never is. A tooling test pins today's
// list, so a new opt-out shows up in review.
export function generatedFiles(rootDir = ROOT, roots = COVERAGE_ROOTS): string[] {
  return roots.flatMap((root) =>
    readdirSync(path.join(rootDir, root), { recursive: true, encoding: 'utf8' })
      .filter((file) => /\.tsx?$/.test(file))
      .map((file) => `${root}/${file.split(path.sep).join('/')}`)
      .filter((file) => {
        const header = readFileSync(path.join(rootDir, file), 'utf8').slice(0, 400);
        return /^\/\/ Generated by /.test(header) && /Do not\s+(?:\/\/\s*)?hand-edit/i.test(header);
      }),
  );
}

export default defineConfig({
  test: {
    passWithNoTests: true,
    projects: [
      'packages/*/vitest.config.ts',
      'apps/*/vitest.config.ts',
      'scripts/vitest.config.ts',
      // T-010 (BR6.2, D10): the seed integration test runs in every combined run so `seed/**` is
      // measured. It resets and seeds `DATABASE_URL_TEST`, which `database` (group 1) also uses,
      // so it runs alone in group 2, after that project ends; groups run one after another
      // (https://vitest.dev/config/sequence#sequence-grouporder, Vitest 4.1.11).
      {
        test: {
          name: 'test-support-seed',
          root: './packages/test-support',
          environment: 'node',
          include: ['src/seed/seed.int.test.ts'],
          fileParallelism: false,
          sequence: { groupOrder: 2 },
          testTimeout: 180_000,
          hookTimeout: 180_000,
        },
      },
    ],
    coverage: {
      provider: 'v8',
      reportsDirectory: 'coverage',
      reporter: ['text-summary', 'json-summary', 'json'],
      // A run with a failing test still prints and writes its figures.
      reportOnFailure: true,
      include: COVERAGE_ROOTS.map((root) => `${root}/**/*.{ts,tsx}`),
      // 80% of lines per package, never lowered (D10, BR6.1, BR6.5). A package with no executable
      // line passes, because Vitest reports 0 of 0 as 100% (BR6.3).
      thresholds: Object.fromEntries(COVERAGE_ROOTS.map((root) => [`${root}/**`, { lines: 80 }])),
      exclude: [
        // Tests, including `*.smoke.test.*` and `*.int.test.ts`: the code under test is measured.
        '**/*.test.ts',
        '**/*.test.tsx',
        // Test setup run by Vitest before the tests, not code the product runs.
        '**/test-setup.ts',
        '**/global-setup.ts',
        // Helpers only tests import (today `packages/database/src/queue/queue-test-support.ts`).
        '**/*-test-support.ts',
        // Type declarations hold no executable lines.
        '**/*.d.ts',
        ...generatedFiles(),
      ],
    },
  },
});
