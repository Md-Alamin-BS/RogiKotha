import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';

import { generatedFiles } from '../vitest.workspace.ts';

// Today's opt-outs (FD-093 (7)): a file added here is excluded from the 80% floor, so it is
// reviewed as a change to the coverage scope.
const GENERATED_TODAY = [
  'packages/i18n/src/keys.ts',
  'packages/test-support/src/corpus/accounts.ts',
  'packages/test-support/src/corpus/aliases.ts',
  'packages/test-support/src/corpus/branches.ts',
  'packages/test-support/src/corpus/comments.ts',
  'packages/test-support/src/corpus/conditions.ts',
  'packages/test-support/src/corpus/config.ts',
  'packages/test-support/src/corpus/doctors.ts',
  'packages/test-support/src/corpus/evidence.ts',
  'packages/test-support/src/corpus/facilities.ts',
  'packages/test-support/src/corpus/facility-reviews.ts',
  'packages/test-support/src/corpus/follow-ups.ts',
  'packages/test-support/src/corpus/moderation.ts',
  'packages/test-support/src/corpus/notifications.ts',
  'packages/test-support/src/corpus/personas.ts',
  'packages/test-support/src/corpus/reviews.ts',
];

const temporaryRoots = [];
const aSourceTree = (files) => {
  const rootDir = mkdtempSync(path.join(tmpdir(), 'coverage-exclusions-'));
  temporaryRoots.push(rootDir);
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(rootDir, file)), { recursive: true });
    writeFileSync(path.join(rootDir, file), text);
  }
  return rootDir;
};

afterEach(() => {
  for (const rootDir of temporaryRoots.splice(0)) rmSync(rootDir, { recursive: true, force: true });
});

describe('the generated-file coverage exclusion', () => {
  it("leaves out exactly today's generated files, so a new opt-out shows up in review", () => {
    expect([...generatedFiles()].sort()).toEqual(GENERATED_TODAY);
  });

  it('leaves out a file whose header says generated and not to hand-edit, wrapped or not', () => {
    const rootDir = aSourceTree({
      'pkg/src/one-line.ts': '// Generated by gen.mjs. Do not hand-edit.\nexport const a = 1;\n',
      'pkg/src/wrapped.ts':
        '// Generated by gen.mjs from data.js. Do not\n// hand-edit.\nexport const b = 1;\n',
    });

    expect(generatedFiles(rootDir, ['pkg/src']).sort()).toEqual([
      'pkg/src/one-line.ts',
      'pkg/src/wrapped.ts',
    ]);
  });

  it('keeps a hand-written file and one whose do-not-edit line is missing or past the header', () => {
    const rootDir = aSourceTree({
      'pkg/src/hand-written.ts': 'export const a = 1;\n',
      'pkg/src/no-warning.ts': '// Generated by gen.mjs.\nexport const b = 1;\n',
      'pkg/src/late-warning.ts': `// Generated by gen.mjs.\n${'// note\n'.repeat(60)}// Do not hand-edit.\n`,
    });

    expect(generatedFiles(rootDir, ['pkg/src'])).toEqual([]);
  });
});
