#!/usr/bin/env node
/*
 * Generates src/keys.ts: a union type of every message key in
 * messages/en.json plus a runtime array of the same. Committed output;
 * `pnpm --filter @rogikotha/i18n check` verifies it is up to date.
 *
 * Run: `pnpm --filter @rogikotha/i18n keys`.
 */

/* eslint-disable no-undef, no-console --
 * Node CLI script printing a summary line; see check-parity.mjs for why.
 * ASSUMPTION(T-006).
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const enPath = path.join(__dirname, '../messages/en.json');
const outPath = path.join(__dirname, '../src/keys.ts');

function flatten(obj, prefix = '') {
  const keys = [];
  for (const [k, v] of Object.entries(obj)) {
    const dotted = prefix ? `${prefix}.${k}` : k;
    if (typeof v === 'string') {
      keys.push(dotted);
    } else if (v && typeof v === 'object') {
      keys.push(...flatten(v, dotted));
    } else {
      throw new Error(`unexpected value at ${dotted}: ${JSON.stringify(v)}`);
    }
  }
  return keys;
}

function main() {
  const en = JSON.parse(fs.readFileSync(enPath, 'utf8'));
  const keys = flatten(en).sort();

  const unionType = keys.map((k) => `  | '${k}'`).join('\n');
  const arrayLiteral = keys.map((k) => `  '${k}',`).join('\n');

  const contents = `// Generated by scripts/gen-keys.mjs from messages/en.json. Do not hand-edit.
// Run \`pnpm --filter @rogikotha/i18n keys\` to regenerate.

export type MessageKey =
${unionType};

export const MESSAGE_KEYS: readonly MessageKey[] = [
${arrayLiteral}
] as const;
`;

  fs.writeFileSync(outPath, contents, 'utf8');
  console.log(`Wrote ${keys.length} keys to src/keys.ts`);
}

main();
